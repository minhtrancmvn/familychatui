#!/usr/bin/env bash

# One-time, idempotent host setup. Run on the server as the admin user (sudo), from a copied deploy/ dir:
#   DOMAIN=chat.example.com bash setup-host.sh     # app user, folders, env file, unit, gate, nginx, certificate
#   DOMAIN=chat.example.com CI_PUBLIC_KEY="ssh-ed25519 AAAA... familychatui-ci" bash setup-host.sh   # + CI key
# Needs the Cloudflare DNS record first (certbot checks it over HTTP). Re-run after changing anything in deploy/.
#
# Layout: code /opt/familychatui (releases/, current, deploy/), data /var/lib/familychatui,
# secrets /etc/familychatui/env. The app runs as `familychat` (no sudo, no access to /home).

set -euo pipefail

DOMAIN="${DOMAIN:?set DOMAIN to the hostname, e.g. chat.example.com}"
DEPLOY_DIR="$(cd "$(dirname "$0")" && pwd)"
ROOT=/opt/familychatui
ADMIN="$(id -un)"

if [[ "$(id -u)" -eq 0 ]]; then
    printf 'Run as the admin user (with sudo), not root.\n' >&2
    exit 1
fi

sudo apt-get install -y -q --no-install-recommends poppler-utils libreoffice-writer-nogui libreoffice-calc-nogui libreoffice-impress-nogui >/dev/null
id familychat >/dev/null 2>&1 || sudo useradd --system --user-group --no-create-home --shell /usr/sbin/nologin familychat

sudo install -d -o "$ADMIN" -g "$ADMIN" -m 755 "$ROOT" "$ROOT/releases" "$ROOT/deploy"
sudo install -o root -g root -m 755 "$DEPLOY_DIR/deploy-gate.sh" "$ROOT/deploy/deploy-gate"
sudo install -o root -g root -m 755 "$DEPLOY_DIR/activate-release.sh" "$ROOT/deploy/activate-release.sh"
sudo install -o root -g root -m 755 "$DEPLOY_DIR/prune-releases.sh" "$ROOT/deploy/prune-releases.sh"
sudo install -o root -g root -m 755 "$DEPLOY_DIR/update-geo-allowlist.py" "$ROOT/deploy/update-geo-allowlist.py"

sudo install -d -o root -g familychat -m 750 /etc/familychatui
if ! sudo test -f /etc/familychatui/env; then
    printf 'NINEROUTER_API_KEY=\nFAMILY_PASSWORD=\n' | sudo install -o root -g familychat -m 640 /dev/stdin /etc/familychatui/env
    printf 'Created /etc/familychatui/env: fill in NINEROUTER_API_KEY and FAMILY_PASSWORD (sudoedit).\n'
fi

sudo install -m 644 "$DEPLOY_DIR/familychatui.service" /etc/systemd/system/familychatui.service
sudo install -m 644 "$DEPLOY_DIR/familychatui-geo.service" /etc/systemd/system/familychatui-geo.service
sudo install -m 644 "$DEPLOY_DIR/familychatui-geo.timer" /etc/systemd/system/familychatui-geo.timer
sudo systemctl daemon-reload
sudo systemctl enable familychatui

if [[ -n "${CI_PUBLIC_KEY:-}" ]]; then
    entry="restrict,command=\"$ROOT/deploy/deploy-gate\" $CI_PUBLIC_KEY"
    grep -qxF "$entry" "$HOME/.ssh/authorized_keys" || printf '%s\n' "$entry" >>"$HOME/.ssh/authorized_keys"
fi

# Keep certbot's 443 edits once the certificate exists; only seed the vhost on first run.
if [[ ! -f "/etc/nginx/sites-available/$DOMAIN" ]]; then
    sed "s/__DOMAIN__/$DOMAIN/g" "$DEPLOY_DIR/nginx-familychatui.conf" | sudo install -m 644 /dev/stdin "/etc/nginx/sites-available/$DOMAIN"
fi
sudo ln -sfn "/etc/nginx/sites-available/$DOMAIN" "/etc/nginx/sites-enabled/$DOMAIN"

# Real visitor IPs for the app's guess limiter (it reads X-Real-IP = $remote_addr): take CF-Connecting-IP
# only from Cloudflare's published ranges, so it can't be faked whether the record is proxied or DNS-only.
ranges="$(curl -fsS https://www.cloudflare.com/ips-v4; echo; curl -fsS https://www.cloudflare.com/ips-v6)"
test "$(grep -c / <<<"$ranges")" -gt 10
{
    printf '# Generated by familychatui deploy/setup-host.sh from https://www.cloudflare.com/ips\n'
    grep / <<<"$ranges" | sed 's/.*/set_real_ip_from &;/'
    printf 'real_ip_header CF-Connecting-IP;\n'
} | sudo tee /etc/nginx/snippets/cloudflare-realip.conf >/dev/null
if ! sudo grep -q cloudflare-realip "/etc/nginx/sites-available/$DOMAIN"; then
    sudo sed -i "0,/server_name $DOMAIN;/s//&\n    include \/etc\/nginx\/snippets\/cloudflare-realip.conf;/" "/etc/nginx/sites-available/$DOMAIN"
fi
if ! sudo grep -q "proxy_set_header CF-Connecting-IP" "/etc/nginx/sites-available/$DOMAIN"; then
    sudo sed -i 's/^\( *\)proxy_set_header X-Real-IP \$remote_addr;/&\n\1proxy_set_header CF-Connecting-IP $remote_addr;/' "/etc/nginx/sites-available/$DOMAIN"
fi
sudo nginx -t
sudo systemctl reload nginx

# HTTP-01 works through the Cloudflare proxy as long as port 80 is not force-redirected to HTTPS.
sudo certbot --nginx --non-interactive --agree-tos --redirect --register-unsafely-without-email -d "$DOMAIN" --keep-until-expiring

# Only Vietnam, Singapore and the US (iCloud Private Relay included) may use the chat site: build the
# allowlist (DB-IP + Apple's relay list, refreshed daily by a timer), then make the HTTPS server answer
# 403 with a short bilingual page to everyone else. Done after certbot so the first server block is the
# HTTPS one; port 80 keeps serving certificate renewals. Other sites on the host are not restricted.
sudo install -m 644 "$DEPLOY_DIR/nginx-familychatui-geo.conf" /etc/nginx/snippets/familychatui-geo.conf
if [[ ! -f /etc/nginx/conf.d/familychatui-geo.conf ]]; then
    sudo python3 "$ROOT/deploy/update-geo-allowlist.py"
fi
sudo systemctl enable --now familychatui-geo.timer
if ! sudo grep -q 'familychatui-geo.conf' "/etc/nginx/sites-available/$DOMAIN"; then
    sudo sed -i '0,/include \/etc\/nginx\/snippets\/cloudflare-realip.conf;/s//&\n    include \/etc\/nginx\/snippets\/familychatui-geo.conf;/' "/etc/nginx/sites-available/$DOMAIN"
fi
sudo nginx -t
sudo systemctl reload nginx

printf '\nHost ready. Deploy with deploy/deploy.sh (or push to main), then check https://%s\n' "$DOMAIN"
