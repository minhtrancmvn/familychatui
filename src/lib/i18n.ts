const DICTS: Record<Lang, Dict> = { en, vi };

export function translate(lang: Lang, key: MsgKey, vars?: Record<string, string | number>): string {
  let text = DICTS[lang][key] ?? en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) text = text.replaceAll(`{${k}}`, String(v));
  return text;
}

export type T = (key: MsgKey, vars?: Record<string, string | number>) => string;

/** The active profile's language; before a profile is chosen, this device's last language. */
export function useLang(): Lang {
  const profile = useActiveProfile();
  const deviceLanguage = useAppStore((s) => s.deviceLanguage);
  return profile?.language ?? deviceLanguage;
}

export function useT(): T {
  const lang = useLang();
  return useCallback((key, vars) => translate(lang, key, vars), [lang]);
}

export function tagKey(tag: ModelTag): MsgKey {
  return `tag.${tag}`;
}
